import fs from 'node:fs/promises'
import path from 'node:path'
import type { Context } from 'koa'
import { type TransitionVideoService, VideoServiceError } from './Service.js'

export function videoRange (header: string, size: number): { start: number, end: number } | null {
  // A single range covers browser seeking. Ignore unsupported units/multi-ranges.
  if (!header || !header.startsWith('bytes=') || header.includes(',')) return null
  const match = /^(\d*)-(\d*)$/.exec(header.slice(6).trim())
  const invalid = () => new VideoServiceError(416, 'El rango solicitado no está disponible.')
  if (!match || (!match[1] && !match[2]) || !size) throw invalid()
  const total = BigInt(size)
  if (!match[1]) {
    const suffix = BigInt(match[2])
    if (!suffix) throw invalid()
    return { start: Number(suffix >= total ? 0n : total - suffix), end: size - 1 }
  }
  const start = BigInt(match[1])
  const end = match[2] ? BigInt(match[2]) : total - 1n
  if (start >= total || end < start) throw invalid()
  return { start: Number(start), end: Number(end >= total ? total - 1n : end) }
}

export async function streamTransitionVideo (ctx: Context, service: TransitionVideoService, poster: boolean) {
  const { row, release } = service.acquire(ctx.user.roomId, ctx.params.id)
  const filename = poster ? row.posterFilename : row.filename
  let file: Awaited<ReturnType<typeof fs.open>> | undefined
  let streaming = false
  try {
    // Filenames are generated by the store, never supplied by the request.
    if (!filename || path.basename(filename) !== filename) throw new VideoServiceError(404, 'El archivo no está disponible.')
    file = await fs.open(path.join(service.directory, filename), 'r')
    const { size } = await file.stat()
    const etag = `"${row.checksum}${poster ? '-poster' : ''}"`
    let range: ReturnType<typeof videoRange> = null
    try {
      if (ctx.method === 'GET' && (!ctx.get('If-Range') || ctx.get('If-Range') === etag)) range = videoRange(ctx.get('Range'), size)
    } catch (error) {
      ctx.set('Content-Range', `bytes */${size}`)
      throw error
    }
    ctx.type = poster ? 'image/jpeg' : 'video/mp4'
    ctx.set('ETag', etag)
    ctx.set('Accept-Ranges', 'bytes')
    ctx.set('X-Content-Type-Options', 'nosniff')
    if (range) ctx.set('Content-Range', `bytes ${range.start}-${range.end}/${size}`)
    if (ctx.method !== 'HEAD') {
      const stream = file.createReadStream(range ?? {})
      stream.once('close', release)
      ctx.body = stream
      streaming = true
    }
    ctx.length = range ? range.end - range.start + 1 : size
    ctx.status = range ? 206 : 200
  } catch (error) {
    if (error instanceof VideoServiceError) throw error
    throw new VideoServiceError(404, 'El archivo no está disponible.')
  } finally {
    if (!streaming) {
      try {
        await file?.close()
      } finally { release() }
    }
  }
}
