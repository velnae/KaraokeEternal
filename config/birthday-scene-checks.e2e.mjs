import assert from 'node:assert/strict'
import fs from 'node:fs'
import { expect } from 'playwright/test'

export async function checkBirthdayScene ({ admin, api, base, calls, birthday, data, event, call }) {
  const upload = await api.post(`${base}api/birthdays/upload`, { multipart: { kind: 'intro', file: { name: 'Alternativa.wav', mimeType: 'audio/wav', buffer: fs.readFileSync(`${data}/greeting.wav`) } } })
  assert.equal(upload.status(), 200)
  const alternate = await upload.json()
  const original = await event(birthday.id)
  const originalIntro = original.assets.find(asset => asset.kind === 'intro')
  const providerCount = calls.length
  const card = admin.getByRole('article', { name: 'Cumpleaños de María', exact: true })
  const panel = admin.getByRole('region', { name: 'Cumpleaños preparados', exact: true })
  const birthdayTrigger = admin.getByRole('button', { name: /^Cumpleaños(?: \(\d+\))?$/ })
  await expect(card.getByRole('button')).toHaveCount(3)
  await expect(card.getByRole('button', { name: 'Configurar celebración', exact: true })).toHaveCount(0)
  await expect(panel.getByRole('link')).toHaveCount(0)
  const listen = card.getByRole('button', { name: 'Escuchar saludo de María', exact: true })
  await listen.focus()
  await admin.keyboard.press('Enter')
  const details = admin.getByRole('dialog', { name: 'Cumpleaños de María', exact: true })
  await expect.poll(() => details.locator('audio').evaluate(audio => audio.currentTime)).toBeGreaterThan(0)
  assert.equal((await event(birthday.id)).playback, 'held', 'Listening privately does not program the event')
  const privateAudio = await details.locator('audio').elementHandle()
  await details.locator('audio').evaluate(audio => audio.dispatchEvent(new Event('error')))
  await expect(details.getByRole('alert')).toContainText('No se pudo abrir')
  await details.getByRole('button', { name: 'Reintentar audio', exact: true }).click()
  await expect.poll(() => details.locator('audio').evaluate(audio => audio.currentTime)).toBeGreaterThan(0)
  for (const width of [390, 1440]) {
    await admin.setViewportSize({ width, height: 900 })
    assert.ok(await details.evaluate(element => element.scrollWidth <= element.clientWidth + 2))
    await admin.screenshot({ path: `${data}/birthday-queue-details-${width}.png` })
  }
  await admin.keyboard.press('Escape')
  await expect(details).toHaveCount(0)
  assert.equal(await privateAudio.evaluate(audio => audio.paused), true)
  await expect(listen).toBeFocused()
  await card.getByRole('button', { name: 'Más opciones de cumpleaños de María', exact: true }).click()
  await details.getByRole('button', { name: 'Configurar celebración', exact: true }).focus()
  await admin.keyboard.press('Enter')
  const editor = admin.getByRole('dialog', { name: 'Celebración de María', exact: true })
  await editor.getByRole('combobox', { name: 'Introducción', exact: true }).selectOption(alternate.id)
  await editor.getByRole('button', { name: 'Aplicar selección', exact: true }).click()
  await expect(editor).toHaveCount(0)
  const manual = await event(birthday.id)
  assert.equal(manual.scene.introMode, 'manual')
  assert.equal(manual.assets.find(asset => asset.kind === 'greeting').id, original.assets.find(asset => asset.kind === 'greeting').id)
  assert.equal(manual.script, original.script)
  await expect(details.getByText(alternate.title, { exact: true })).toHaveCount(1)
  await details.getByRole('button', { name: 'Configurar celebración', exact: true }).click()
  await editor.getByRole('button', { name: 'Volver a la propuesta automática', exact: true }).click()
  await expect(editor).toHaveCount(0)
  assert.equal((await event(birthday.id)).assets.find(asset => asset.kind === 'intro').id, originalIntro.id)
  await expect(card.getByRole('button', { name: 'Previsualizar celebración', exact: true })).toHaveCount(0)
  await expect(card.getByRole('button', { name: 'Escuchar prueba', exact: true })).toHaveCount(0)
  await expect(details).toBeVisible()
  await admin.keyboard.press('Escape')
  await expect(details).toHaveCount(0)
  const operationPattern = `**/api/birthdays/events/${birthday.id}`
  await admin.keyboard.press('Escape')
  await admin.getByRole('button', { name: /^Por aprobar/ }).click()
  await birthdayTrigger.click()
  const refuse = route => route.fulfill({ status: 409, body: 'El cumpleaños cambió. Actualice antes de programar.' })
  await admin.route(operationPattern, refuse)
  await card.getByRole('button', { name: 'Programar', exact: true }).click()
  await expect(panel.getByRole('alert')).toContainText('El cumpleaños cambió')
  assert.equal((await event(birthday.id)).playback, 'held')
  await admin.unroute(operationPattern, refuse)
  await card.getByRole('button', { name: 'Programar', exact: true }).focus()
  await admin.keyboard.press('Enter')
  await expect.poll(async () => (await event(birthday.id)).playback).toBe('scheduled')
  await expect(admin).toHaveURL(/[?&]view=queue/)
  await expect(panel).toHaveCount(0)
  await expect(card).toHaveCount(1)
  await expect(card.getByRole('button', { name: 'Retirar', exact: true })).toBeVisible()
  const queuedOptions = card.getByRole('button', { name: 'Más opciones de cumpleaños de María', exact: true })
  await queuedOptions.click()
  await expect(details.getByRole('button', { name: 'Retirar', exact: true })).toBeVisible()
  await expect(details.getByRole('button', { name: 'Editar datos', exact: true })).toHaveCount(0)
  await admin.keyboard.press('Escape')
  await expect(details).toHaveCount(0)
  await expect(queuedOptions).toBeFocused()
  for (const width of [390, 1440]) {
    await admin.setViewportSize({ width, height: 900 })
    await card.scrollIntoViewIfNeeded()
    assert.ok(await admin.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    await admin.screenshot({ path: `${data}/birthday-queue-scheduled-${width}.png` })
  }
  await card.getByRole('button', { name: 'Retirar', exact: true }).click()
  await expect.poll(async () => (await event(birthday.id)).playback).toBe('held')
  await birthdayTrigger.click()
  await expect(panel.getByRole('article')).toHaveCount(1)
  await expect(admin.locator('[data-birthday-id]')).toHaveCount(0)
  assert.equal(calls.length, providerCount, 'Scene adjustments never call providers')
  const current = await event(birthday.id)
  assert.equal(current.playback, 'held')
  birthday.revision = current.revision
  // Keep the alternative available for bank management without changing playback fixtures.
  const overview = await call('birthdays/')
  await call('birthdays/settings', { ...overview.settings, introIds: [originalIntro.id, alternate.id] }, 'PUT')
}
