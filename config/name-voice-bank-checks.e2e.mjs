import { request, expect } from 'playwright/test'
import fs from 'node:fs'
import path from 'node:path'
import assert from 'node:assert/strict'

export async function checkNameVoiceBank ({ page, browser, base, uiBase, data, db, call, join, add, emit, connect, proxy, fail }) {
  await page.goto(uiBase + 'admin/settings/animator?view=names')
  const bank = page.getByRole('region', { name: 'Banco global de nombres' })
  await expect(bank.getByRole('heading', { name: 'Nombres', exact: true })).toBeVisible()
  await expect(bank.getByText('Todas las salas', { exact: true })).toBeVisible()
  const initialStyle = await call('name-voices/style')
  const customStyle = 'Pronounce only the supplied name clearly in Latin American Spanish, with a resonant, well-supported voice at normal announcement volume. No whispering or extra words.'
  const jobsBeforeStyle = db.prepare('SELECT count(*) n FROM karaokeCallJobs').get().n
  const budgetBeforeStyle = db.prepare('SELECT count(*) n FROM greetingVoiceRequests').get().n
  await page.goto(uiBase + 'admin/settings/audio-providers?use=names')
  const voiceSettings = page.getByRole('region', { name: 'Configuración de nombres', exact: true })
  let styleForm = voiceSettings.getByRole('form', { name: 'Estilo para nombres' })
  await styleForm.getByRole('combobox', { name: 'Modelo para nuevas generaciones' }).selectOption('gemini-3.8-flash-tts')
  await styleForm.getByLabel('Estilo para nuevas generaciones', { exact: true }).fill(customStyle)
  await styleForm.getByRole('button', { name: 'Guardar configuración', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(styleForm.getByRole('status')).toHaveText('Configuración guardada.')
  await page.reload()
  styleForm = voiceSettings.getByRole('form', { name: 'Estilo para nombres' })
  await expect(styleForm.getByRole('combobox', { name: 'Modelo para nuevas generaciones' })).toHaveValue('gemini-3.8-flash-tts')
  const modelSelect = styleForm.getByRole('combobox', { name: 'Modelo para nuevas generaciones' })
  await modelSelect.focus()
  await page.keyboard.press('Home')
  await page.keyboard.press('Tab')
  await expect(modelSelect).toHaveValue('gemini-3.8-flash-lite-tts')
  await expect(styleForm.getByLabel('Estilo para nuevas generaciones', { exact: true })).toHaveValue(customStyle)
  await styleForm.getByRole('button', { name: 'Cargar estilo predeterminado', exact: true }).click()
  await expect(styleForm.getByLabel('Estilo para nuevas generaciones', { exact: true })).toHaveValue(initialStyle.defaultStyle)
  assert.equal((await call('name-voices/style')).style, customStyle)
  await styleForm.getByRole('button', { name: 'Descartar cambios', exact: true }).click()
  await expect(modelSelect).toHaveValue('gemini-3.8-flash-tts')
  await expect(styleForm.getByLabel('Estilo para nuevas generaciones', { exact: true })).toHaveValue(customStyle)
  assert.equal(db.prepare('SELECT count(*) n FROM karaokeCallJobs').get().n, jobsBeforeStyle)
  assert.equal(db.prepare('SELECT count(*) n FROM greetingVoiceRequests').get().n, budgetBeforeStyle)
  for (const width of [390, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    await styleForm.scrollIntoViewIfNeeded()
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
    await page.screenshot({ path: path.join(data, `name-style-${width}.png`), fullPage: true })
  }
  await page.goto(uiBase + 'admin/settings/animator?view=names')
  await expect(bank.getByRole('link', { name: 'Configurar voz de nombres' })).toBeVisible()
  const before = db.prepare('SELECT count(*) n FROM animationInterventions').get().n
  // Create without synthesis; the existing John alias must require explicit reassignment.
  const orphanGroup = await call('name-voices', { spokenText: 'John' })
  await bank.getByRole('button', { name: 'Nueva pronunciación' }).focus()
  await page.keyboard.press('Enter')
  let editor = page.getByRole('dialog', { name: 'Nueva pronunciación' })
  await editor.getByLabel('Pronunciación', { exact: true }).fill('Yon')
  await editor.getByRole('button', { name: 'Crear pronunciación', exact: true }).click()
  editor = page.getByRole('dialog', { name: 'Gestionar pronunciación' })
  await editor.getByLabel('Nombres asociados').fill('John\nJhon\nIon')
  await editor.getByRole('button', { name: 'Guardar cambios' }).click()
  await expect(editor.getByRole('alert')).toContainText('reasignación')
  await editor.getByRole('checkbox', { name: 'Reasignar: John' }).check()
  await editor.getByRole('button', { name: 'Guardar cambios' }).click()
  await expect(editor.getByRole('alert')).toHaveCount(0)
  await expect.poll(async () => (await call('name-voices?q=Ion')).items.some(item => item.spokenText === 'Yon')).toBe(true)
  const group = (await call('name-voices?q=Ion')).items.find(item => item.spokenText === 'Yon')
  assert.ok(group)
  const details = () => call(`name-voices/${group.id}`)
  const paid = () => db.prepare(`SELECT count(*) n FROM karaokeCallJobs WHERE operation='source'
    AND json_extract(inputJSON,'$.nameId')=? AND json_extract(inputJSON,'$.nameReprocessId') IS NULL`).get(group.id).n
  assert.equal(paid(), 0)
  await editor.getByRole('button', { name: 'Generar voz', exact: true }).click()
  await expect(editor.getByRole('button', { name: 'Usar versión 1 de Yon' })).toBeVisible({ timeout: 20000 })
  assert.equal((await details()).active, null)
  await editor.getByRole('button', { name: 'Usar versión 1 de Yon' }).focus()
  await page.keyboard.press('Enter')
  await expect.poll(async () => (await details()).active?.part.id).toBeTruthy()
  const selected = (await details()).active.part.id
  await editor.getByText('Instrucciones de generación', { exact: true }).click()
  await expect(editor.getByText(customStyle, { exact: true })).toBeVisible()
  assert.equal((await details()).active.style, customStyle)
  assert.equal((await details()).active.model, 'gemini-3.8-flash-tts')
  await editor.getByRole('button', { name: 'Escuchar versión 1 de Yon' }).click()
  await expect.poll(() => editor.locator('audio').evaluate(audio => audio.readyState)).toBeGreaterThanOrEqual(2)
  await editor.locator('audio').evaluate(audio => audio.play())
  await expect.poll(() => editor.locator('audio').evaluate(audio => audio.ended)).toBe(true)
  await editor.getByRole('button', { name: 'Cerrar escucha' }).click()
  await expect(editor.getByRole('button', { name: 'Escuchar versión 1 de Yon' })).toBeFocused()
  assert.equal((await details()).uses, 0)
  assert.equal(db.prepare('SELECT count(*) n FROM animationInterventions').get().n, before)

  fail('Yon')
  await editor.getByRole('button', { name: 'Regenerar voz', exact: true }).click()
  await expect.poll(async () => (await details()).job?.status, { timeout: 20000 }).toBe('uncertain')
  await expect(editor.getByRole('alert')).toBeVisible()
  fail('')
  assert.equal((await details()).active.part.id, selected)
  assert.equal(paid(), 2)
  await editor.getByRole('button', { name: 'Reprocesar nivel', exact: true }).click()
  await expect.poll(async () => (await details()).versions.length, { timeout: 15000 }).toBe(2)
  assert.equal((await details()).active.part.id, selected)
  assert.equal(paid(), 2)
  await page.keyboard.press('Escape')
  await expect(editor).not.toBeVisible()
  await expect(bank.getByRole('button', { name: 'Nueva pronunciación' })).toBeFocused()

  // A second room uses the selected global audio for Ion, with a real public
  // call/greeting sequence but no further name synthesis.
  db.prepare(`INSERT INTO rooms(roomId,name,status,data) SELECT 2,'Second room','open',data FROM rooms WHERE roomId=1`).run()
  db.prepare('INSERT INTO karaokeCallControls(roomId,listeningEnabled) VALUES(2,1)').run()
  await call('rooms/2/tables', { code: '01' })
  const ion = await join('Ion', '01', 2)
  const api2 = await request.newContext()
  let context2
  try {
    const login = await api2.post(base + 'api/login', { data: { username: 'admin', password: 'call-pilot-test', roomId: 2 } })
    assert.equal(login.status(), 200)
    const operator2 = await connect(await api2.storageState())
    const bankState = await (await api2.get(base + 'api/rooms/2/karaoke-calls')).json()
    const bank = await api2.post(base + 'api/rooms/2/karaoke-calls/setup', { data: { requestId: crypto.randomUUID(), revision: bankState.automation.controls.revision, quote: bankState.automation.bankQuote } })
    assert.equal(bank.status(), 202)
    await expect.poll(async () => (await (await api2.get(base + 'api/rooms/2/karaoke-calls')).json()).automation.bankPreparing, { timeout: 30000 }).toBe(false)
    await emit(operator2, 'server/GREETINGS', { operation: 'prepareAudio', enabled: true })
    await emit(operator2, 'server/GREETINGS', { operation: 'playback', version: 0, settings: { enabled: true, introClipId: null, ambienceEnabled: false } })
    const queueId = await add(ion, 16, 'LISTEN')
    await emit(ion, 'server/GREETINGS', { operation: 'attach', queueId, message: '¡Una noche especial!' })
    await expect.poll(() => db.prepare('SELECT resultId FROM listeningPresentations WHERE queueId=?').get(queueId)?.resultId, { timeout: 30000 }).toBeTruthy()
    assert.equal(db.prepare('SELECT namePartId FROM listeningPresentations WHERE queueId=?').get(queueId).namePartId, selected)
    assert.equal(paid(), 2)
    context2 = await browser.newContext({ storageState: await api2.storageState(), viewport: { width: 1440, height: 1000 } })
    if (uiBase !== base) await proxy(context2, api2)
    const identity = await (await api2.get(base + 'api/user')).json()
    await context2.addInitScript(identity => localStorage.setItem('persist:user', JSON.stringify(Object.fromEntries(Object.entries(identity).map(([key, value]) => [key, JSON.stringify(value)])))), identity)
    const player2 = await context2.newPage()
    await player2.goto(uiBase + 'player')
    await expect.poll(async () => (await emit(operator2, 'server/ANIMATION_SYNC')).payload.playerPresent).toBe(true)
    await player2.locator('body').click({ position: { x: 10, y: 10 } })
    await emit(operator2, 'server/PLAYER_REQ_PLAY')
    await expect.poll(() => db.prepare('SELECT status FROM queue WHERE queueId=?').get(queueId)?.status, { timeout: 30000 }).toBe('PLAYED')
    const intervention = db.prepare(`SELECT * FROM animationInterventions WHERE json_extract(callJSON,'$.queueId')=?`).get(queueId)
    assert.equal(intervention.status, 'PLAYED')
    assert.equal(db.prepare('SELECT voiceStatus FROM greetingTurns WHERE turnKey=?').get(queueId).voiceStatus, 'PLAYED')
    await expect.poll(async () => (await details()).uses).toBe(1)
    assert.ok((await details()).lastUsedAt)
    assert.equal(paid(), 2)
    fs.writeFileSync(path.join(data, 'name-bank-room-two.json'), JSON.stringify({ queueId, selected, intervention,
      trace: await player2.evaluate(() => window.karaokePlaybackTrace.snapshot()) }, null, 2))
  } finally {
    fail('')
    await context2?.close()
    await api2.dispose()
  }
  await bank.getByLabel('Buscar nombre').fill('Ion')
  await expect(bank.getByRole('button', { name: 'Gestionar Yon' })).toBeVisible()
  await bank.getByRole('button', { name: 'Gestionar Yon' }).click()
  editor = page.getByRole('dialog', { name: 'Gestionar pronunciación' })
  await editor.getByRole('checkbox', { name: 'Archivada', exact: true }).check()
  await editor.getByRole('button', { name: 'Guardar cambios' }).click()
  await expect.poll(async () => (await details()).archived).toBe(true)
  assert.equal((await details()).versions.length, 2)
  await editor.getByRole('checkbox', { name: 'Archivada', exact: true }).uncheck()
  await editor.getByRole('button', { name: 'Guardar cambios' }).click()
  await expect.poll(async () => (await details()).archived).toBe(false)
  for (const width of [390, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
    await page.screenshot({ path: path.join(data, `name-bank-editor-${width}.png`), fullPage: true })
  }
  await page.keyboard.press('Escape')
  await bank.getByLabel('Buscar nombre').fill('John')
  await bank.getByRole('button', { name: 'Gestionar John', exact: true }).click()
  const orphan = page.getByRole('dialog', { name: 'Gestionar pronunciación' })
  await orphan.getByRole('checkbox', { name: 'Archivada', exact: true }).check()
  await orphan.getByRole('button', { name: 'Guardar cambios' }).click()
  await expect.poll(async () => (await call(`name-voices/${orphanGroup.id}`)).archived).toBe(true)
  await expect.poll(async () => (await details()).aliases.includes('John')).toBe(true)
  await expect(orphan.getByRole('button', { name: 'Guardar cambios' })).toBeEnabled()
  await page.keyboard.press('Escape')
  await bank.getByLabel('Buscar nombre').fill('Ion')
  for (const width of [390, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    await bank.scrollIntoViewIfNeeded()
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
    await page.screenshot({ path: path.join(data, `name-bank-list-${width}.png`), fullPage: true })
  }
  console.log('Global name bank: global prompt style save/reload/reset without synthesis, exact generation instructions, alias reassignment, private preview, versions, local reprocessing, cross-room playback, confirmed usage, archive, keyboard and responsive layouts passed.')
}
