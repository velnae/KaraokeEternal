import { expect } from 'playwright/test'
import assert from 'node:assert/strict'
import { expandSceneProperties, sceneTemplateAction, sceneBlockAction } from './event-scene-test-helpers.e2e.mjs'

export async function checkSceneAuthoring ({ player, call, effect, background }) {
  const canvas = player.getByLabel('Lienzo de la escena', { exact: true })
  const preview = player.getByRole('region', { name: 'Vista previa de la coreografía', exact: true })
  await player.getByRole('button', { name: 'Agregar texto', exact: true }).click()
  await player.getByRole('textbox', { name: 'Texto', exact: true }).fill('{name}\nPróximo turno')
  await expandSceneProperties(player)
  await player.getByLabel('Posición X (%)').fill('15')
  await player.getByLabel('Ancho (%)', { exact: true }).fill('60')
  await player.getByLabel('Tamaño del texto (FHD)').fill('100')
  await player.getByLabel('Color del texto', { exact: true }).fill('#ffee00')
  await player.getByLabel('Alineación').selectOption('left')
  const text = canvas.getByRole('button', { name: 'Editar Texto', exact: true })
  await expect(text).toContainText('Alex')
  await expect(text).toHaveCSS('color', 'rgb(255, 238, 0)')
  const id = await text.getAttribute('data-scene-cue')
  const box = await text.boundingBox()
  await player.mouse.move(box.x + 20, box.y + 20)
  await player.mouse.down()
  await player.mouse.move(box.x + 50, box.y + 35, { steps: 5 })
  await player.mouse.up()
  const moved = Number(await player.getByLabel('Posición X (%)').inputValue())
  assert.ok(moved > 15, 'canvas drag moves the text in normalized coordinates')
  await player.getByRole('button', { name: 'Deshacer', exact: true }).click()
  await expect(player.getByLabel('Posición X (%)')).toHaveValue('15')
  await player.getByRole('button', { name: 'Rehacer', exact: true }).click()
  await expect.poll(async () => Number(await player.getByLabel('Posición X (%)').inputValue())).toBeGreaterThan(15)
  await text.focus()
  const beforeKey = Number(await player.getByLabel('Posición X (%)').inputValue())
  await player.keyboard.press('ArrowRight')
  await expect.poll(async () => Number(await player.getByLabel('Posición X (%)').inputValue())).toBeGreaterThan(beforeKey)
  await player.getByRole('button', { name: 'Duplicar elemento', exact: true }).click()
  await expect(canvas.getByRole('button', { name: 'Editar Texto', exact: true })).toHaveCount(2)
  await player.getByRole('button', { name: 'Quitar de la escena', exact: true }).click()
  await expect(player.getByRole('slider', { name: 'Cursor de la línea de tiempo', exact: true })).toBeFocused()
  await expect(canvas.getByRole('button', { name: 'Editar Texto', exact: true })).toHaveCount(1)
  await text.click()
  await expandSceneProperties(player)
  await player.getByLabel('Posición Y (%)').fill('72')
  const before = (await call('animation/scenes/')).audio.map(item => item.id)
  await player.getByRole('button', { name: 'Agregar audio', exact: true }).click()
  const dialog = player.getByRole('dialog')
  await dialog.getByRole('searchbox').fill(effect.title)
  await dialog.getByRole('button', { name: `Agregar ${effect.title}`, exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await player.getByRole('button', { name: 'Quitar de la escena', exact: true }).click()
  assert.deepEqual((await call('animation/scenes/')).audio.map(item => item.id), before, 'removing a scene block must not delete a catalog resource')
  await player.getByRole('button', { name: 'Deshacer', exact: true }).click()
  await player.getByRole('button', { name: 'Agregar video', exact: true }).click()
  const videoDialog = player.getByRole('dialog')
  const videoTitle = (await call('animation/scenes/')).videos.find(item => item.id === background.id).title
  await videoDialog.getByRole('button', { name: `Agregar ${videoTitle}`, exact: true }).click()
  await player.getByLabel('Desplazamiento (s)', { exact: true }).fill('1')
  await player.getByLabel('Duración (s)', { exact: true }).fill('0.5')
  await player.getByRole('group', { name: 'Línea de tiempo', exact: true }).getByRole('button', { name: 'Datos del evento', exact: true }).click()
  await player.getByRole('button', { name: 'Separar datos para editar', exact: true }).click()
  await expect(canvas.getByRole('button', { name: 'Editar Nombre', exact: true })).toBeVisible()
  await canvas.getByRole('button', { name: 'Editar Nombre', exact: true }).click()
  await expandSceneProperties(player)
  await player.getByLabel('Tamaño del texto (FHD)').fill('110')
  await player.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(player.getByText('Coreografía guardada.', { exact: true })).toBeVisible()
  const saved = (await call('animation/scenes/')).settings.templates.find(scene => scene.id === 'transition')
  assert.equal(saved.cues.find(cue => cue.id === id).layout.color, '#ffee00')
  assert.ok(saved.cues.some(cue => cue.binding === 'resource' && cue.resourceId === effect.id))
  assert.equal(saved.cues.find(cue => cue.text === '{name}').layout.fontSize, 110)
  const videoCueId = saved.cues.find(cue => cue.binding === 'resource' && cue.lane === 'background').id
  const effectCueId = saved.cues.find(cue => cue.binding === 'resource' && cue.resourceId === effect.id).id
  const timeline = player.getByRole('group', { name: 'Línea de tiempo', exact: true })
  await timeline.getByRole('button', { name: effect.title, exact: true }).click()
  await player.getByRole('combobox', { name: /^Referencia/ }).selectOption('block:announcement')
  await player.getByRole('combobox', { name: /^Momento del bloque/ }).selectOption('end')
  await player.getByLabel('Desplazamiento (s)', { exact: true }).fill('0.2')
  const blockActions = player.getByLabel('Más acciones del bloque', { exact: true })
  await blockActions.focus()
  await blockActions.press('Enter')
  await expect(player.getByRole('button', { name: 'Mover antes', exact: true })).toBeVisible()
  await blockActions.press('Escape')
  await expect(blockActions).toBeFocused()
  await expect(player.getByRole('button', { name: 'Mover antes', exact: true })).not.toBeVisible()
  for (let index = 0; index < 3; index++) await sceneBlockAction(player, 'Mover antes')
  await timeline.getByRole('button', { name: 'Nombre', exact: true }).click()
  await player.getByRole('combobox', { name: /^Referencia/ }).selectOption(`block:${effectCueId}`)
  await player.getByRole('combobox', { name: /^Momento del bloque/ }).selectOption('start')
  const offset = player.getByLabel('Desplazamiento (s)', { exact: true })
  await player.getByRole('combobox', { name: 'Desplazamiento', exact: true }).selectOption('before')
  await offset.fill('0.4')
  await offset.press('ArrowUp')
  await expect(offset).toHaveValue('0.5')
  await player.getByLabel('Duración (s)', { exact: true }).fill('0.6')
  await timeline.getByRole('button', { name: effect.title, exact: true }).click()
  await player.getByRole('button', { name: 'Quitar de la escena', exact: true }).click()
  await expect(player.getByRole('alert')).toContainText('Cambie la referencia de «Nombre»')
  await player.getByRole('button', { name: 'Guardar', exact: true }).click()
  await expect(player.getByText('Coreografía guardada.', { exact: true })).toBeVisible()
  const related = (await call('animation/scenes/')).settings.templates.find(scene => scene.id === 'transition')
  assert.equal(related.cues.find(cue => cue.id === effectCueId).referenceId, 'announcement')
  assert.equal(related.cues.find(cue => cue.id === effectCueId).referenceEdge, 'end')
  assert.equal(related.cues.find(cue => cue.text === '{name}').referenceId, effectCueId)
  assert.equal(related.cues.find(cue => cue.text === '{name}').offsetMs, -500)
  const cursor = preview.getByRole('slider', { name: 'Posición de la vista previa', exact: true })
  await cursor.press('Home')
  for (let index = 0; index < 11; index++) await cursor.press('ArrowRight')
  await expect(canvas.locator('[data-background-cue]')).toHaveAttribute('data-background-cue', videoCueId)
  await cursor.press('Home')
  for (let index = 0; index < 21; index++) await cursor.press('ArrowRight')
  assert.notEqual(await canvas.locator('[data-background-cue]').getAttribute('data-background-cue'), videoCueId, 'seeking evaluates the actual active background')
  await cursor.focus()
  await cursor.press('Home')
  for (let index = 0; index < 22; index++) await cursor.press('ArrowRight')
  await expect(preview.getByRole('status', { name: 'Tiempo de la vista previa' })).toContainText('2.2')
  await preview.getByRole('button', { name: 'Continuar', exact: true }).click()
  await expect(preview.getByRole('button', { name: 'Pausar', exact: true })).toBeVisible()
  await preview.getByRole('button', { name: 'Pausar', exact: true }).click()
  const paused = await preview.getByRole('status', { name: 'Tiempo de la vista previa' }).textContent()
  await player.waitForTimeout(150)
  assert.equal(await preview.getByRole('status', { name: 'Tiempo de la vista previa' }).textContent(), paused)
  await preview.getByRole('button', { name: 'Detener', exact: true }).click()
  await expect(preview.getByRole('status', { name: 'Tiempo de la vista previa' })).toContainText('0.0')
  const templateCount = (await call('animation/scenes/')).settings.templates.length
  await player.getByRole('combobox', { name: 'Evento', exact: true }).selectOption('listen')
  await sceneTemplateAction(player, 'Nueva')
  await sceneTemplateAction(player, 'Eliminar plantilla')
  const save = player.getByRole('button', { name: 'Guardar', exact: true })
  if (await save.isEnabled()) {
    await save.click()
    await expect(player.getByText('Coreografía guardada.', { exact: true })).toBeVisible()
  } else await expect(player.getByRole('group', { name: 'Guardar coreografía' }).getByRole('status')).toHaveText('Guardado')
  assert.equal((await call('animation/scenes/')).settings.templates.length, templateCount, 'an unselected template can be created and removed without inventing a selected binding')
  await player.getByRole('combobox', { name: 'Evento', exact: true }).selectOption('transition')
  return { textId: id, effectId: effect.id, videoCueId, effectCueId, leadTextId: related.cues.find(cue => cue.text === '{name}').id }
}
