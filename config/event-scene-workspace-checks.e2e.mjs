import { expect } from 'playwright/test'
import assert from 'node:assert/strict'
import path from 'node:path'

export async function checkSceneWorkspace ({ player, uiBase, call, data }) {
  const editor = player.getByRole('region', { name: 'Coreografías', exact: true })
  const timeline = player.getByRole('group', { name: 'Línea de tiempo', exact: true })
  const preview = player.getByRole('region', { name: 'Vista previa de la coreografía', exact: true })
  const canvas = player.getByLabel('Lienzo de la escena', { exact: true })
  const tabs = player.getByRole('navigation', { name: 'Ajustes del animador', exact: true })
  const saveBar = player.getByRole('group', { name: 'Guardar coreografía', exact: true })
  const save = saveBar.getByRole('button', { name: 'Guardar', exact: true })
  const discard = saveBar.getByRole('button', { name: 'Descartar cambios', exact: true })
  const iconOnly = async (control) => {
    await expect(control).toHaveText('')
    await expect(control.locator('svg')).toHaveCount(1)
    assert.ok(await control.getAttribute('aria-label'))
    const box = await control.boundingBox()
    assert.ok(box.width >= 44 && box.width <= 48 && box.height >= 44 && box.height <= 48, 'icon-only action keeps a square touch target')
  }
  await expect(save).toBeDisabled()
  await expect(discard).toBeDisabled()
  await expect(saveBar.getByRole('status')).toHaveText('Guardado')
  await expect(editor.getByRole('button', { name: 'Guardar y usar', exact: true })).toBeVisible()
  await expect(editor.getByRole('button', { name: 'Usar', exact: true })).toHaveCount(0)
  await expect(editor.getByRole('button', { name: 'Nueva', exact: true })).not.toBeVisible()
  const menu = player.getByLabel('Acciones de plantilla', { exact: true })
  await iconOnly(menu)
  for (const name of ['Deshacer', 'Rehacer']) await iconOnly(editor.getByRole('button', { name, exact: true }))
  for (const name of ['Previsualizar', 'Detener', 'Pantalla completa']) await iconOnly(preview.getByRole('button', { name, exact: true }))
  await expect(save).toHaveText('Guardar')
  await expect(discard).toHaveText('Descartar cambios')
  await menu.focus()
  await menu.press('Enter')
  await expect(editor.getByRole('button', { name: 'Nueva', exact: true })).toBeVisible()
  await menu.press('Escape')
  await expect(menu).toBeFocused()
  await expect(editor.getByRole('button', { name: 'Nueva', exact: true })).not.toBeVisible()
  const measurements = []
  for (const [width, height] of [[1440, 1000], [1920, 1080], [390, 844]]) {
    await player.setViewportSize({ width, height })
    await player.locator('main').evaluate(node => node.scrollTo({ top: 0 }))
    const box = await timeline.boundingBox()
    const frame = await canvas.boundingBox()
    const inspector = await editor.locator('aside').boundingBox()
    measurements.push({ width, timelineTop: Math.round(box.y), previewWidth: Math.round(frame.width), inspectorWidth: Math.round(inspector.width) })
    if (width >= 1440) {
      assert.ok(frame.width >= (width === 1440 ? 650 : 1000), 'desktop preview uses available width')
      assert.ok(inspector.width >= 380 && inspector.width <= 461, 'desktop properties use the wider column')
      assert.ok(inspector.height >= frame.height, 'properties use the preview row height')
    }
    assert.ok(box.height <= 370, 'timeline has its own bounded scrolling area')
    const buttons = await saveBar.getByRole('button').evaluateAll(nodes => nodes.map(node => ({ height: node.getBoundingClientRect().height, border: parseFloat(getComputedStyle(node).borderTopWidth), background: getComputedStyle(node).backgroundColor })))
    assert.ok(buttons.every(button => button.height >= 44 && button.border > 0 && button.background !== 'rgba(0, 0, 0, 0)'), 'save/discard actions have visible button surfaces and touch-sized targets')
    const nav = await tabs.boundingBox()
    const links = await tabs.getByRole('link').evaluateAll(nodes => nodes.map(node => node.getBoundingClientRect().y))
    assert.ok(Math.max(...links) - Math.min(...links) < 2, 'local navigation stays on a single line')
    const active = await tabs.getByRole('link', { name: 'Coreografías', exact: true }).boundingBox()
    assert.ok(active.x >= nav.x - 1 && active.x + active.width <= nav.x + nav.width + 1)
    assert.ok(await player.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
    await player.screenshot({ path: path.join(data, `scene-workspace-overview-${width}.png`) })
  }

  await player.getByRole('button', { name: 'Agregar texto', exact: true }).click()
  const properties = player.getByRole('region', { name: 'Propiedades del elemento', exact: true })
  await expect(properties.getByRole('textbox', { name: 'Texto', exact: true })).toBeVisible()
  for (const name of ['Duplicar elemento', 'Quitar de la escena']) await iconOnly(properties.getByRole('button', { name, exact: true }))
  await expect(properties.getByLabel('Tamaño del texto (FHD)')).not.toBeVisible()
  await expect(properties.getByLabel('Posición X (%)')).not.toBeVisible()
  const mobileInspector = await properties.boundingBox()
  const mobileTimeline = await timeline.boundingBox()
  assert.ok(mobileInspector.y >= mobileTimeline.y + mobileTimeline.height, 'mobile properties follow the timeline')
  await properties.getByText('Formato', { exact: true }).focus()
  await player.keyboard.press('Enter')
  await properties.getByLabel('Tamaño del texto (FHD)').fill('96')
  await properties.getByText('Posición y animación', { exact: true }).focus()
  await player.keyboard.press('Space')
  await properties.getByLabel('Posición X (%)').fill('12')
  await expect(properties.getByLabel('Posición X (%)')).toHaveValue('12')
  await expect(save).toBeEnabled()
  await expect(discard).toBeEnabled()
  await expect(saveBar.getByRole('status')).toHaveText('Cambios sin guardar')
  await timeline.evaluate(node => node.scrollIntoView({ block: 'center' }))
  await expect.poll(() => saveBar.evaluate((node) => {
    const main = node.closest('main')
    return Math.abs(node.getBoundingClientRect().top - main.getBoundingClientRect().top - parseFloat(getComputedStyle(main).paddingTop)) < 2
  })).toBe(true)

  const timing = player.getByRole('region', { name: 'Tiempo del bloque', exact: true })
  await timing.getByRole('combobox', { name: 'Referencia', exact: true }).selectOption('block:announcement')
  await timing.getByRole('combobox', { name: 'Momento del bloque', exact: true }).selectOption('start')
  await timing.getByRole('combobox', { name: 'Desplazamiento', exact: true }).selectOption('before')
  await timing.getByLabel('Desplazamiento (s)', { exact: true }).fill('0.5')
  for (const [width, height] of [[1440, 1000], [390, 844]]) {
    await player.setViewportSize({ width, height })
    await timing.screenshot({ path: path.join(data, `scene-workspace-timing-${width}.png`) })
    if (width === 1440) {
      const direction = await timing.getByRole('combobox', { name: 'Desplazamiento', exact: true }).boundingBox()
      const edge = await timing.getByRole('combobox', { name: 'Momento del bloque', exact: true }).boundingBox()
      assert.ok(Math.abs(direction.y - edge.y) < 2, 'sentence controls stay inline on desktop')
    }
  }
  await iconOnly(preview.getByLabel('Opciones de vista', { exact: true }))
  await preview.getByLabel('Opciones de vista', { exact: true }).focus()
  await player.keyboard.press('Enter')
  await preview.getByRole('combobox', { name: 'Resolución', exact: true }).selectOption('1280')
  await expect(canvas.locator('div').first()).toHaveAttribute('style', /width: 1280px/)
  await preview.getByLabel('Opciones de vista', { exact: true }).click()
  await expect(preview.getByRole('combobox', { name: 'Resolución', exact: true })).not.toBeVisible()
  await player.getByRole('button', { name: 'Descartar cambios', exact: true }).click()

  await player.getByRole('button', { name: 'Agregar audio', exact: true }).click()
  const dialog = player.getByRole('dialog')
  await iconOnly(dialog.getByRole('button', { name: 'Actualizar biblioteca', exact: true }))
  await iconOnly(dialog.getByRole('button', { name: /^Agregar / }).first())
  await dialog.getByRole('searchbox').fill('NO-MATCH-FOR-WORKSPACE-CHECK')
  await expect(dialog.getByRole('status')).toHaveText('Sin coincidencias.')
  await dialog.getByRole('button', { name: 'Limpiar búsqueda', exact: true }).click()
  await expect(dialog.getByRole('searchbox')).toHaveValue('')
  await expect(dialog.getByRole('status')).toHaveCount(0)
  await dialog.screenshot({ path: path.join(data, 'scene-workspace-library.png') })
  await dialog.getByRole('button', { name: 'Cerrar', exact: true }).click()

  const overview = await call('animation/scenes/')
  const pattern = '**/api/animation/scenes/'
  await player.route(pattern, route => route.fulfill({ json: { ...overview, audio: [], videos: [] } }))
  try {
    await player.reload()
    await player.getByRole('button', { name: 'Agregar audio', exact: true }).click()
    await expect(dialog.getByRole('status')).toHaveText('No hay audios disponibles.')
    await expect(dialog.getByRole('link', { name: 'Abrir biblioteca', exact: true })).toHaveCount(1)
    await expect(dialog.getByRole('button', { name: 'Limpiar búsqueda', exact: true })).toHaveCount(0)
    await dialog.screenshot({ path: path.join(data, 'scene-workspace-empty-library.png') })
    await dialog.getByRole('button', { name: 'Cerrar', exact: true }).click()
  } finally { await player.unroute(pattern) }
  await player.setViewportSize({ width: 1440, height: 1000 })
  await player.goto(`${uiBase}admin/settings/animator?view=scenes`)
  await player.getByRole('combobox', { name: 'Evento', exact: true }).selectOption('transition')
  console.log(`PASS compact workspace, action hierarchy, disclosure keyboard, mobile inspector, time sentence, view options and search states: ${JSON.stringify(measurements)}`)
}
