import { expect } from 'playwright/test'
import assert from 'node:assert/strict'
import path from 'node:path'
import fs from 'node:fs'

export async function checkPhraseBank ({ editor, call, uiBase, data }) {
  // Keep clock-driven assertions independent of concurrent development rebuilds.
  await editor.route('**/__webpack_hmr', route => route.fulfill({ status: 200, contentType: 'text/event-stream', body: '' }))
  await editor.clock.install()
  await editor.goto(`${uiBase}account?roomId=1&redirect=${encodeURIComponent('/admin/settings/display')}`)
  await editor.getByRole('button', { name: 'Tengo una cuenta', exact: true }).click()
  await editor.getByPlaceholder('nombre de usuario o correo electrónico').fill('admin')
  await editor.getByPlaceholder('contraseña', { exact: true }).fill('branding-test-password')
  await editor.getByRole('button', { name: 'Iniciar sesión', exact: true }).click()
  const form = editor.getByRole('form', { name: 'Configuración de pantalla' })
  const tab = name => form.getByRole('button', { name, exact: true }).click()
  const save = async () => {
    await form.getByRole('button', { name: 'Aplicar cambios', exact: true }).click()
    await expect(form.getByText('Cambios guardados.', { exact: true })).toBeVisible()
  }
  await tab('Frases')
  const bank = form.getByRole('textbox', { name: 'Frases (una por línea, hasta 100 caracteres cada una)' })
  await bank.fill(`Primera frase\n\n${'x'.repeat(101)}`)
  await form.getByRole('button', { name: 'Aplicar cambios', exact: true }).click()
  await expect(form.getByRole('alert')).toContainText('Línea 3')
  await expect(bank).toBeFocused()
  await bank.fill(' Primera frase \n\nSegunda frase')
  await expect(form.getByText('2 frases', { exact: true })).toBeVisible()
  await save()
  assert.deepEqual((await call('prefs')).playerDisplay.announcement.phrases, ['Primera frase', 'Segunda frase'])
  await editor.reload()
  await tab('Frases')
  await expect(bank).toHaveValue('Primera frase\nSegunda frase')
  for (const width of [1920, 390]) {
    await editor.setViewportSize({ width, height: 1080 })
    await bank.scrollIntoViewIfNeeded()
    await editor.screenshot({ path: path.join(data, `phrase-bank-${width}.png`), fullPage: true })
    assert.ok(await editor.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  }
  await editor.setViewportSize({ width: 1920, height: 1080 })
  await tab('Comunicados')
  await form.getByRole('checkbox', { name: 'Mostrar comunicados durante música para escuchar', exact: true }).check()
  const enabled = form.getByRole('checkbox', { name: 'Mostrar una frase al finalizar los comunicados', exact: true })
  await expect(enabled).not.toBeChecked()
  await enabled.focus()
  await enabled.press('Space')
  await expect(enabled).toBeChecked()
  await form.getByRole('spinbutton', { name: 'Intervalo entre mensajes (s)', exact: true }).fill('5')
  await form.getByLabel('Título del comunicado 1', { exact: true }).fill('Aviso uno')
  await form.getByRole('button', { name: 'Agregar comunicado', exact: true }).click()
  await form.getByLabel('Título del comunicado 2', { exact: true }).fill('Aviso dos')
  await expect(form.getByRole('checkbox', { name: /Mostrar icono QR/ })).toHaveCount(0)
  const firstMessage = form.getByRole('group', { name: 'Comunicado 1', exact: true })
  const secondMessage = form.getByRole('group', { name: 'Comunicado 2', exact: true })
  await expect(firstMessage.getByRole('img', { name: 'Imagen del comunicado 1', exact: true })).toBeVisible()
  await expect(secondMessage.getByRole('img')).toHaveCount(0)
  const png = await editor.evaluate(() => {
    const canvas = document.createElement('canvas')
    canvas.width = 120
    canvas.height = 80
    const context = canvas.getContext('2d')
    context.fillStyle = '#76e0ec'
    context.fillRect(0, 0, 120, 80)
    context.fillStyle = '#030509'
    context.font = 'bold 24px sans-serif'
    context.fillText('IL GATTO', 4, 48)
    return canvas.toDataURL('image/png').split(',')[1]
  })
  const imagePath = path.join(data, 'logo.png')
  fs.writeFileSync(imagePath, Buffer.from(png, 'base64'))
  await form.getByLabel('Seleccionar PNG del comunicado 2', { exact: true }).setInputFiles(imagePath)
  await expect(form.getByRole('img', { name: 'Imagen del comunicado 2', exact: true })).toBeVisible()
  await expect(form.getByText('Preparando imagen…', { exact: true })).toHaveCount(0)
  await firstMessage.getByRole('spinbutton', { name: 'Tamaño de imagen del comunicado 1 (%)', exact: true }).fill('200')
  await secondMessage.getByRole('spinbutton', { name: 'Tamaño de imagen del comunicado 2 (%)', exact: true }).fill('75')
  await save()
  const saved = (await call('prefs')).playerDisplay
  assert.equal(saved.announcement.messages[0].imageScale, 200)
  assert.equal(saved.announcement.messages[1].imageScale, 75)
  assert.equal(saved.announcement.messages[0].image, 'qr')
  assert.match(saved.announcement.messages[1].image, /^[a-f\d-]{36}$/)
  await editor.reload()
  await tab('Comunicados')
  await expect(form.getByRole('img', { name: 'Imagen del comunicado 2', exact: true })).toBeVisible()
  await expect(firstMessage.getByRole('spinbutton')).toHaveValue('200')
  await expect(secondMessage.getByRole('spinbutton')).toHaveValue('75')
  for (const width of [1920, 390]) {
    await editor.setViewportSize({ width, height: 1080 })
    await form.getByRole('group', { name: 'Comunicado 2', exact: true }).screenshot({ path: path.join(data, `announcement-images-${width}.png`) })
    await firstMessage.screenshot({ path: path.join(data, `announcement-qr-control-${width}.png`) })
    assert.ok(await editor.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  }
  await editor.setViewportSize({ width: 1920, height: 1080 })
  const scene = form.getByLabel('Contenido de la vista previa', { exact: true })
  await scene.selectOption('SING')
  await expect(form.getByRole('region', { name: 'Comunicados del local' })).toHaveCount(0)
  await editor.clock.pauseAt(await editor.evaluate(() => Date.now() + 1000))
  await scene.selectOption('LISTEN')
  const banner = form.getByRole('region', { name: 'Comunicados del local' })
  const current = banner.locator('[aria-hidden="false"]')
  const imageSize = firstMessage.getByRole('spinbutton', { name: 'Tamaño de imagen del comunicado 1 (%)', exact: true })
  await imageSize.fill('100')
  await expect(banner.locator('img')).toHaveCSS('width', '36px')
  for (const width of [1920, 390]) {
    await editor.setViewportSize({ width, height: 1080 })
    await imageSize.fill('100')
    const before = await banner.boundingBox()
    const textBefore = await current.boundingBox()
    await imageSize.fill('2000')
    await expect(banner.locator('img')).toHaveCSS('width', '720px')
    assert.deepEqual(await banner.boundingBox(), before, 'image scaling must not resize or move the announcement')
    assert.deepEqual(await current.boundingBox(), textBefore, 'image scaling must not reflow the text')
    const imageBounds = await banner.locator('img').boundingBox()
    assert.ok(imageBounds.height > before.height * 2, 'image can be substantially taller than the announcement')
    assert.ok(imageBounds.x < before.x, 'large image extends outside the announcement')
    await expect(banner).toHaveCSS('overflow', 'visible')
    await form.getByRole('figure', { name: 'Vista previa de pantalla' }).screenshot({ path: path.join(data, `announcement-overflow-${width}.png`), animations: 'disabled' })
  }
  await editor.setViewportSize({ width: 1920, height: 1080 })
  await imageSize.fill('100')
  await firstMessage.getByRole('slider').focus()
  await editor.keyboard.press('ArrowRight')
  await expect(imageSize).toHaveValue('105')
  await imageSize.fill('200')
  await expect(banner.locator('img')).toHaveCSS('width', '72px')
  for (const text of ['Aviso uno', 'Aviso dos', 'Primera frase', 'Aviso uno', 'Aviso dos', 'Segunda frase', 'Aviso uno', 'Aviso dos', 'Primera frase']) {
    await expect(current).toContainText(text)
    await expect(banner.locator('svg')).toHaveCount(0)
    await expect(banner.locator('img')).toHaveCount(text.startsWith('Aviso') ? 1 : 0)
    if (text.startsWith('Aviso')) await expect(banner.locator('img')).toHaveCSS('width', text === 'Aviso uno' ? '72px' : '27px')
    if (text === 'Aviso dos') await expect.poll(() => banner.locator('img').evaluate(image => image.naturalWidth)).toBe(120)
    await banner.screenshot({ path: path.join(data, `announcement-${text.replaceAll(' ', '-')}.png`), animations: 'disabled' })
    await editor.clock.runFor(5000)
  }
  await secondMessage.getByRole('button', { name: 'Quitar imagen', exact: true }).click()
  await scene.selectOption('SING')
  await scene.selectOption('LISTEN')
  await editor.clock.runFor(5000)
  await expect(current).toContainText('Aviso dos')
  await expect(banner.locator('img')).toHaveCount(0)
  await expect(banner.locator('svg')).toHaveCount(0)
  await save()
  assert.equal((await call('prefs')).playerDisplay.announcement.messages[1].image, null)
  await firstMessage.getByRole('button', { name: 'Quitar imagen', exact: true }).focus()
  await editor.keyboard.press('Enter')
  await save()
  assert.equal((await call('prefs')).playerDisplay.announcement.messages[0].image, null)
  await expect(firstMessage.getByRole('img')).toHaveCount(0)
  await firstMessage.getByLabel('Seleccionar PNG del comunicado 1', { exact: true }).setInputFiles(imagePath)
  await expect(firstMessage.getByRole('img')).toHaveAttribute('src', /player-logo-images/)
  await expect(form.getByText('Preparando imagen…', { exact: true })).toHaveCount(0)
  await save()
  assert.match((await call('prefs')).playerDisplay.announcement.messages[0].image, /^[a-f\d-]{36}$/)
  assert.equal((await call('prefs')).playerDisplay.announcement.messages[0].imageScale, 200)
  await firstMessage.getByRole('button', { name: 'Quitar imagen', exact: true }).focus()
  await editor.keyboard.press('Enter')
  await save()
  assert.equal((await call('prefs')).playerDisplay.announcement.messages[0].image, null)
  await expect(firstMessage.getByRole('img')).toHaveCount(0)
  await enabled.uncheck()
  await scene.selectOption('SING')
  await scene.selectOption('LISTEN')
  for (const text of ['Aviso uno', 'Aviso dos', 'Aviso uno']) {
    await expect(current).toContainText(text)
    await editor.clock.runFor(5000)
  }
  await enabled.check()
  await tab('Frases')
  await bank.fill('')
  await tab('Comunicados')
  await expect(form.getByText('Agregue frases en la pestaña Frases para mostrarlas.')).toBeVisible()
  await scene.selectOption('SING')
  await scene.selectOption('LISTEN')
  for (const text of ['Aviso uno', 'Aviso dos', 'Aviso uno']) {
    await expect(current).toContainText(text)
    await editor.clock.runFor(5000)
  }
}
