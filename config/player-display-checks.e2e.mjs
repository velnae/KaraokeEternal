import { expect } from 'playwright/test'
import assert from 'node:assert/strict'
import path from 'node:path'
import { installYouTubeTransitionFixture } from './transition-ambience-checks.e2e.mjs'

const login = async (page, base, roomId, redirect) => {
  await page.goto(`${base}account?roomId=${roomId}&redirect=${encodeURIComponent(redirect)}`)
  await page.getByRole('button', { name: 'Tengo una cuenta', exact: true }).click()
  await page.getByPlaceholder('nombre de usuario o correo electrónico').fill('admin')
  await page.getByPlaceholder('contraseña', { exact: true }).fill('branding-test-password')
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click()
}

export async function checkPlayerDisplay ({ browser, editor, player, secondApi, call, emit, db, base, uiBase, data, realYouTube, errors }) {
  const logoSrc = await editor.evaluate(() => {
    const canvas = document.createElement('canvas')
    canvas.width = 360
    canvas.height = 144
    const ctx = canvas.getContext('2d')
    ctx.fillStyle = '#76e0ec'
    ctx.fillRect(0, 0, 360, 144)
    ctx.fillStyle = '#030509'
    ctx.font = 'bold 48px sans-serif'
    ctx.textAlign = 'center'
    ctx.fillText('IL GATTO', 180, 90)
    return canvas.toDataURL('image/png')
  })
  const defaults = (await call('prefs')).playerDisplay
  const brand = { name: 'Il Gatto', logoSrc, supportUrl: '' }
  await call('prefs/branding', brand, 'PUT')
  await login(editor, uiBase, 1, '/admin/settings/display')
  await expect(editor.getByRole('heading', { name: 'Pantalla del reproductor', exact: true })).toBeVisible()
  await expect(editor.getByText('Todo el local · Referencia FHD (1920 × 1080)', { exact: true })).toBeVisible()
  const form = editor.getByRole('form', { name: 'Configuración de pantalla' })
  const group = name => form.getByRole('button', { name, exact: true }).click()
  const number = (label, value) => form.getByRole('spinbutton', { name: label, exact: true }).fill(String(value))
  const save = async () => {
    await form.getByRole('button', { name: 'Aplicar cambios', exact: true }).click()
    await expect(form.getByText('Cambios guardados.', { exact: true })).toBeVisible()
  }
  const preview = form.getByRole('figure', { name: 'Vista previa de pantalla' })
  await expect(preview.getByRole('combobox', { name: 'Resolución de vista previa' })).toHaveValue('1920')
  await player.goto(`${uiBase}player`)
  await expect(player.getByTestId('player-display-overlay')).toHaveCount(0)
  await player.getByRole('button', { name: 'Reproducir', exact: true }).last().click()
  await expect(player.getByTestId('transition-scene')).toBeVisible()
  await expect(player.getByTestId('player-display-overlay')).toHaveCount(0)
  const playing = async (id) => {
    await expect.poll(() => db.prepare('SELECT status FROM queue WHERE queueId=?').get(id)?.status, { timeout: 30000 }).toBe('PLAYING')
    await expect(player.getByTestId('transition-scene')).toHaveCount(0, { timeout: 30000 })
    await expect(player.getByTestId('player-display-overlay')).toBeVisible({ timeout: 30000 })
  }
  await playing(1)
  const media = player.locator(realYouTube ? 'iframe' : 'video:not([data-media-role="transition-background"])')
  const initialBounds = await media.boundingBox()
  await media.evaluate((element) => {
    window.displayMedia = element
  })
  const banner = player.getByRole('region', { name: 'Comunicados del local' })
  const logo = player.getByRole('img', { name: 'Logo de Il Gatto' })
  await expect(banner).toHaveCount(0)
  await expect(logo).toHaveCount(0)
  const toggle = form.getByRole('checkbox', { name: 'Mostrar logo en el reproductor' })
  await toggle.focus()
  await toggle.press('Space')
  await number('Tamaño del logo (%)', 125)
  await number('Margen lateral del logo (%)', 3)
  await number('Margen vertical del logo (%)', 4)
  await number('Opacidad del logo (%)', 80)
  await form.getByLabel('Posición del logo', { exact: true }).selectOption('top-left')
  await group('Comunicados')
  await form.getByRole('checkbox', { name: 'Mostrar comunicados durante música para escuchar' }).check()
  await number('Ancho del comunicado (%)', 45)
  await number('Desplazamiento horizontal (%)', 1)
  await number('Margen vertical del comunicado (%)', 5)
  await number('Espacio interior (FHD)', 24)
  await number('Intervalo entre mensajes (s)', 5)
  await form.getByLabel('Posición del comunicado', { exact: true }).selectOption('bottom-center')
  await form.getByRole('button', { name: 'Agregar comunicado' }).click()
  await form.getByRole('button', { name: 'Aplicar cambios' }).click()
  await expect(form.getByLabel('Título del comunicado 2')).toBeFocused()
  await form.getByLabel('Título del comunicado 2').fill('Disfruta la noche con nosotros')
  await form.getByLabel('Texto del comunicado 2 (opcional)').fill('Tu próxima canción empieza en tu mesa.')
  await form.getByRole('group', { name: 'Comunicado 1', exact: true }).getByRole('button', { name: 'Quitar imagen', exact: true }).click()
  await group('Apariencia')
  const alignment = form.getByLabel('Alineación del contenido')
  await alignment.focus()
  await alignment.press('End')
  await alignment.press('Enter')
  await number('Tamaño del texto (%)', 110)
  const color = form.getByLabel('Color de fondo del comunicado', { exact: true })
  await color.fill('#oops')
  await form.getByRole('button', { name: 'Aplicar cambios' }).click()
  await expect(color).toBeFocused()
  await form.getByRole('button', { name: 'Usar marrón suave' }).click()
  await number('Opacidad del fondo (%)', 88)
  await form.getByText('Borde y sombra', { exact: true }).click()
  await number('Grosor del borde (FHD)', 2)
  await form.getByLabel('Color del borde', { exact: true }).fill('#8a7163')
  await number('Redondeado de esquinas (FHD)', 20)
  await form.getByRole('checkbox', { name: 'Mostrar sombra' }).uncheck()
  await form.getByRole('checkbox', { name: 'Color de texto automático' }).uncheck()
  await form.getByLabel('Color del texto', { exact: true }).fill('#fff1df')
  const scene = preview.getByLabel('Contenido de la vista previa')
  await scene.selectOption('SING')
  await expect(preview.getByRole('region', { name: 'Comunicados del local' })).toHaveCount(0)
  await scene.selectOption('TRANSITION')
  await expect(preview.getByTestId('player-display-overlay')).toHaveCount(0)
  await scene.selectOption('LISTEN')
  await expect(logo).toHaveCount(0)
  await save()
  await expect(logo).toBeVisible()
  await expect(banner).toBeVisible()
  await expect(player.getByText('Para cantar, escanee el QR de su mesa', { exact: true })).toHaveCount(0)
  await expect(banner.locator('svg')).toHaveCount(0)
  await expect(banner).toHaveCSS('color', 'rgb(255, 241, 223)')
  await expect(banner.locator('[aria-hidden="false"] > strong')).toHaveCSS('text-align', 'center')
  await expect(logo).toHaveCSS('opacity', '0.8')
  assert.deepEqual(await media.boundingBox(), initialBounds)
  assert.equal(await media.evaluate(element => element === window.displayMedia), true)
  if (!realYouTube) assert.ok(await media.evaluate(element => !element.paused && element.currentTime > 0))
  const saved = (await call('prefs')).playerDisplay
  assert.equal(saved.logo.scale, 125)
  assert.equal(saved.announcement.width, 45)
  assert.equal(saved.announcement.intervalSeconds, 5)
  await editor.reload()
  await group('Comunicados')
  await expect(form.getByLabel('Título del comunicado 2')).toHaveValue(saved.announcement.messages[1].title)
  await form.getByRole('button', { name: 'Quitar comunicado 2' }).click()
  await form.getByRole('button', { name: 'Descartar' }).click()
  await expect(form.getByLabel('Título del comunicado 2')).toHaveValue(saved.announcement.messages[1].title)
  await number('Ancho del comunicado (%)', 60)
  await editor.route('**/api/prefs/player-display', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: 'No se pudo guardar. Reintente.' }) }))
  await form.getByRole('button', { name: 'Aplicar cambios' }).click()
  await expect(form.getByRole('alert')).toBeVisible()
  await expect(form.getByRole('spinbutton', { name: 'Ancho del comunicado (%)', exact: true })).toHaveValue('60')
  assert.deepEqual((await call('prefs')).playerDisplay, saved)
  await editor.unroute('**/api/prefs/player-display')
  await form.getByRole('button', { name: 'Descartar' }).click()
  await form.getByRole('button', { name: 'Restablecer apariencia' }).click()
  await save()
  const reset = (await call('prefs')).playerDisplay
  assert.equal(reset.logo.scale, defaults.logo.scale)
  assert.equal(reset.logo.enabled, true)
  assert.equal(reset.announcement.enabled, true)
  assert.deepEqual(reset.announcement.messages, saved.announcement.messages)
  assert.equal(reset.announcement.intervalSeconds, 5)
  await call('prefs/player-display', saved, 'PUT')
  await group('Apariencia')
  await expect(color).toHaveValue('#6b5143')
  await group('Comunicados')
  for (let index = 3; index <= 5; index++) {
    await form.getByRole('button', { name: 'Agregar comunicado' }).click()
    await form.getByLabel(`Título del comunicado ${index}`).fill(`Aviso ${index}`)
  }
  await expect(form.getByRole('button', { name: 'Agregar comunicado' })).toHaveCount(0)
  await form.getByRole('button', { name: 'Descartar' }).click()
  await group('Apariencia')
  for (const width of [1920, 390]) {
    await editor.setViewportSize({ width, height: 1080 })
    await preview.screenshot({ path: path.join(data, `editor-preview-${width}.png`) })
    await form.locator('fieldset').first().screenshot({ path: path.join(data, `editor-controls-${width}.png`) })
    assert.ok(await editor.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  }
  await editor.setViewportSize({ width: 1920, height: 1080 })
  await player.keyboard.press('Control+Alt+k')
  await expect.poll(() => player.evaluate(() => document.fullscreenElement?.id)).toBe('player-fs-container')
  const dimensions = []
  for (const width of [1280, 1920, 3840]) {
    const height = width * 9 / 16
    await player.setViewportSize({ width, height })
    await expect.poll(() => player.locator('#player-fs-container').evaluate(element => element.style.width)).toBe(`${width}px`)
    await expect.poll(() => player.locator('#player-fs-container').evaluate(element => element.style.height)).toBe(`${height}px`)
    await preview.getByLabel('Resolución de vista previa').selectOption(String(width))
    const canvas = preview.getByTestId('display-preview-canvas')
    await expect(canvas).toHaveAttribute('data-resolution', `${width}x${height}`)
    const actual = await banner.boundingBox()
    const rendered = await preview.getByRole('region', { name: 'Comunicados del local' }).boundingBox()
    const canvasBounds = await canvas.boundingBox()
    assert.ok(Math.abs(rendered.width / canvasBounds.width - actual.width / width) < 0.002, 'preview matches the real logical viewport')
    dimensions.push({ width, logo: (await logo.boundingBox()).width, banner: actual.width })
    assert.ok(actual.x >= 0 && actual.x + actual.width <= width && actual.y >= 0 && actual.y + actual.height <= height)
    await player.screenshot({ path: path.join(data, `player-${width}.png`) })
  }
  assert.ok(Math.abs(dimensions[2].logo / dimensions[1].logo - 2) < 0.01)
  assert.ok(Math.abs(dimensions[2].banner / dimensions[1].banner - 2) < 0.01)
  await player.setViewportSize({ width: 1280, height: 720 })
  await expect.poll(() => player.locator('#player-fs-container').evaluate(element => element.style.width)).toBe('1280px')
  await call('prefs/player-display', { ...saved, announcement: { ...saved.announcement, width: 20, textScale: 180, padding: 60, marginY: 20,
    messages: [{ title: 'W'.repeat(60), text: 'W'.repeat(100), image: 'qr' }] } }, 'PUT')
  await expect(banner).toContainText('W'.repeat(60))
  await expect.poll(() => banner.evaluate(element => element.scrollHeight <= element.clientHeight + 1)).toBe(true)
  await expect(banner.locator('[aria-hidden="false"] > strong').locator('..')).toHaveCSS('opacity', '1')
  await player.screenshot({ path: path.join(data, 'player-long-message.png') })
  await call('prefs/player-display', { ...saved, announcement: { ...saved.announcement, backgroundColor: '#eeeeee', backgroundOpacity: 100, textColor: null } }, 'PUT')
  await expect(banner).toHaveCSS('color', 'rgb(3, 5, 9)')
  await call('prefs/player-display', saved, 'PUT')
  await player.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => player.locator('#player-fs-container').evaluate(element => element.style.width)).toBe('390px')
  await player.screenshot({ path: path.join(data, 'player-mobile.png') })
  assert.ok(await player.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await player.setViewportSize({ width: 1920, height: 1080 })
  await player.evaluate(() => document.exitFullscreen())
  await expect.poll(() => media.boundingBox()).toEqual(initialBounds)
  await preview.getByLabel('Fondo de prueba').selectOption('light')
  await preview.screenshot({ path: path.join(data, 'preview-light.png') })
  await player.emulateMedia({ reducedMotion: 'reduce' })
  await expect(banner).toHaveCSS('animation-name', 'none')
  await expect(banner.locator('[aria-hidden="false"] > strong').locator('..')).toHaveCSS('transition-duration', '0s')
  await player.emulateMedia({ reducedMotion: 'no-preference' })

  const secondContext = await browser.newContext({ viewport: { width: 1280, height: 720 }, storageState: await secondApi.storageState() })
  await installYouTubeTransitionFixture(secondContext, path.join(data, 'song.mp4'))
  const second = await secondContext.newPage()
  second.on('pageerror', error => errors.push(error.message))
  await login(second, base, 2, '/player')
  await second.getByRole('button', { name: 'Reproducir', exact: true }).last().click()
  const secondLogo = second.getByRole('img', { name: 'Logo de Il Gatto' })
  await expect(secondLogo).toBeVisible({ timeout: 20000 })
  await secondContext.setOffline(true)
  await call('prefs/player-display', { ...saved, logo: { ...saved.logo, opacity: 55 } }, 'PUT')
  await expect(logo).toHaveCSS('opacity', '0.55')
  await secondContext.setOffline(false)
  await expect(secondLogo).toHaveCSS('opacity', '0.55', { timeout: 20000 })
  await call('prefs/player-display', { ...saved, logo: { ...saved.logo, enabled: false } }, 'PUT')
  await expect(logo).toHaveCount(0)
  await expect(secondLogo).toHaveCount(0)
  await expect(banner).toBeVisible()
  await call('prefs/player-display', { ...saved, announcement: { ...saved.announcement, enabled: false } }, 'PUT')
  await expect(logo).toBeVisible()
  await expect(banner).toHaveCount(0)
  await call('prefs/player-display', saved, 'PUT')
  const currentTitle = banner.locator('[aria-hidden="false"] > strong')
  await expect(currentTitle).toBeVisible()
  const first = await currentTitle.textContent()
  const stableHeight = (await banner.boundingBox()).height
  await expect(currentTitle).not.toHaveText(first, { timeout: 8000 })
  assert.equal((await banner.boundingBox()).height, stableHeight)
  await emit('server/PLAYER_REQ_PAUSE')
  const paused = await currentTitle.textContent()
  await player.waitForTimeout(5500)
  await expect(currentTitle).toHaveText(paused)
  await emit('server/PLAYER_REQ_PLAY')
  const beforeIdentity = (await call('prefs')).playerDisplay
  await editor.goto(`${uiBase}admin/settings/branding`)
  await expect(editor.getByRole('checkbox', { name: 'Mostrar logo en el reproductor' })).toHaveCount(0)
  await expect(editor.getByRole('link', { name: 'Configurar pantalla del reproductor' })).toBeVisible()
  await editor.getByRole('button', { name: 'Restablecer marca', exact: true }).click()
  await editor.getByRole('button', { name: 'Guardar cambios', exact: true }).click()
  await expect(logo).toHaveCount(0)
  await expect(banner).toBeVisible()
  assert.deepEqual((await call('prefs')).playerDisplay, beforeIdentity)
  await call('prefs/branding', brand, 'PUT')
  await expect(logo).toBeVisible()
  if (!realYouTube) {
    await player.evaluate(() => window.displayMock.options.events.onAutoplayBlocked({ target: window.displayMock }))
    const recovery = player.getByRole('button', { name: 'Reproducir aquí', exact: true })
    await expect(recovery).toBeVisible()
    await player.screenshot({ path: path.join(data, 'autoplay-recovery.png') })
    await recovery.focus()
    await recovery.press('Enter')
    await expect(recovery).toHaveCount(0)
  }
  for (const id of [2, 3]) {
    await emit('server/PLAYER_REQ_NEXT')
    await expect(player.getByTestId('transition-scene')).toBeVisible()
    await expect(player.getByTestId('player-display-overlay')).toHaveCount(0)
    await playing(id)
    await expect(logo).toBeVisible()
    await expect(banner).toHaveCount(0)
    const card = player.locator('[data-position]')
    await expect(card).toHaveCSS('opacity', '1')
    const cardBox = await card.boundingBox()
    const logoBox = await logo.boundingBox()
    assert.ok(cardBox.x + cardBox.width <= logoBox.x || logoBox.x + logoBox.width <= cardBox.x || cardBox.y + cardBox.height <= logoBox.y || logoBox.y + logoBox.height <= cardBox.y, 'turn card avoids configured logo')
  }
  if (!realYouTube) {
    await player.evaluate(() => window.displayMock.options.events.onError({ target: window.displayMock, data: 150 }))
    await expect.poll(() => db.prepare('SELECT status FROM queue WHERE queueId=3').get().status).toBe('FAILED')
  } else await emit('server/PLAYER_REQ_NEXT')
  await expect.poll(() => db.prepare('SELECT status FROM queue WHERE queueId=4').get().status, { timeout: 20000 }).toBe('PLAYING')
  await expect(player.getByTestId('transition-scene')).toHaveCount(0, { timeout: 20000 })
  await expect(player.getByTestId('player-display-overlay')).toHaveCount(0)
  assert.equal(await player.evaluate(() => window.displayTransitionOverlap), false)
  console.log('PASS UI settings, validation/failure/discard/reset, FHD preview, proportional HD/FHD/4K, mobile, fullscreen, reduced motion, two-room live updates/reconnect, identity independence, rotation/pause and playback gates')
}
