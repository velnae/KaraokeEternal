import assert from 'node:assert/strict'
import fs from 'node:fs'
import { expect } from 'playwright/test'

export async function checkBirthdayPreview ({ admin, api, base, calls, data }) {
  const snapshot = async () => (await api.get(`${base}api/birthdays/`)).json()
  const before = await snapshot()
  const response = await api.post(`${base}api/birthdays/upload`, { multipart: { kind: 'music', file: { name: 'Cierre alternativo.wav', mimeType: 'audio/wav', buffer: fs.readFileSync(`${data}/music.wav`) } } })
  assert.equal(response.status(), 200)
  const music = await response.json()
  const videoResponse = await api.post(`${base}api/birthdays/video/upload`, { multipart: { file: { name: 'Fondo alternativo.mp4', mimeType: 'video/mp4', buffer: fs.readFileSync(`${data}/song.mp4`) } } })
  assert.equal(videoResponse.status(), 200)
  const video = await videoResponse.json()
  await admin.reload()
  await admin.evaluate(() => {
    window.birthdayPreviewBeds = []
    window.birthdayPreviewMedia = []
    const mediaSource = AudioContext.prototype.createMediaElementSource
    AudioContext.prototype.createMediaElementSource = function (element) {
      const source = mediaSource.call(this, element)
      const connect = source.connect.bind(source)
      source.connect = (gain, ...rest) => {
        window.birthdayPreviewMedia.push({ element, gain, context: this })
        return connect(gain, ...rest)
      }
      return source
    }
    const create = AudioContext.prototype.createBufferSource
    AudioContext.prototype.createBufferSource = function () {
      const source = create.call(this)
      const start = source.start.bind(source)
      const disconnect = source.disconnect.bind(source)
      const record = { stopped: false }
      source.start = (...args) => {
        if (source.loop) window.birthdayPreviewBeds.push(record)
        return start(...args)
      }
      source.disconnect = (...args) => {
        record.stopped = true
        return disconnect(...args)
      }
      return source
    }
  })
  const providerCount = calls.length
  await admin.getByRole('button', { name: 'Previsualizar cumpleaños', exact: true }).focus()
  await admin.keyboard.press('Enter')
  const preview = admin.getByRole('dialog', { name: 'Previsualizar cumpleaños', exact: true })
  const play = () => preview.getByRole('button', { name: 'Reproducir', exact: true })
  const audio = () => preview.locator('audio')
  const stage = preview.locator('section[aria-label^="Cumpleaños de "]')
  const text = preview.getByRole('textbox', { name: 'Saludo de prueba', exact: true })
  const name = preview.getByRole('textbox', { name: 'Nombre de prueba', exact: true })
  const generate = preview.getByRole('button', { name: 'Generar audio', exact: true })
  await expect(name).toHaveValue('Carlos')
  assert.ok((await text.inputValue()).split(/\s+/).length <= 45)
  assert.ok((await text.inputValue()).endsWith('¡feliz cumpleaños, Carlos!'))
  await expect(play()).toBeDisabled()
  await expect(preview.getByText('Genere el audio para probar el saludo con este nombre, texto y voz.', { exact: true })).toBeVisible()
  await preview.getByRole('combobox', { name: 'Música final', exact: true }).selectOption(music.id)
  await preview.getByRole('combobox', { name: 'Video de fondo', exact: true }).selectOption(video.id)
  const introductions = preview.getByRole('combobox', { name: 'Introducción', exact: true })
  const alternateIntro = before.assets.find(asset => asset.kind === 'intro' && asset.id !== before.settings.introId)
  assert.ok(alternateIntro)
  await introductions.selectOption(alternateIntro.id)
  assert.equal(calls.length, providerCount, 'Selecting variants must not generate audio')
  let releaseGeneration
  const generationGate = new Promise((resolve) => {
    releaseGeneration = resolve
  })
  let requested = 0
  const delayAudition = async (route) => {
    requested++
    await generationGate
    await route.fallback()
  }
  await admin.route('**/api/birthdays/audition', delayAudition)
  await generate.focus()
  await admin.keyboard.press('Enter')
  await expect.poll(() => requested).toBe(1)
  await preview.getByRole('button', { name: 'Cerrar previsualización', exact: true }).click()
  await admin.getByRole('button', { name: 'Previsualizar cumpleaños', exact: true }).click()
  await expect(preview.getByRole('status').filter({ hasText: 'Generando saludo de prueba…' })).toBeVisible()
  assert.equal(requested, 1, 'Reopening must retain the pending request')
  await expect(introductions).toHaveValue(alternateIntro.id)
  releaseGeneration()
  await expect(play()).toBeEnabled({ timeout: 20000 })
  await admin.unroute('**/api/birthdays/audition', delayAudition)
  assert.equal(calls.length, providerCount + 1, 'The initial sample needs speech only')
  const preparedCount = calls.length
  await generate.click()
  assert.equal(calls.length, preparedCount, 'Generating an identical prepared sample must reuse its audio')
  const preparedText = await text.inputValue()
  await preview.getByRole('button', { name: 'Cerrar previsualización', exact: true }).click()
  await admin.getByRole('button', { name: 'Previsualizar cumpleaños', exact: true }).click()
  await expect(text).toHaveValue(preparedText)
  await expect(play()).toBeEnabled()
  assert.equal(calls.length, preparedCount, 'Reopening a prepared preview must not call providers')
  assert.equal(await preview.locator('video').evaluate(video => video.muted), true)
  await play().click()
  await expect(preview.getByRole('status').filter({ hasText: /^Entrada musical$/ })).toBeVisible()
  await expect(stage).toHaveCount(0)
  await expect.poll(() => admin.evaluate(() => window.birthdayPreviewBeds.filter(bed => !bed.stopped).length)).toBe(1)
  await preview.getByRole('button', { name: 'Pausar', exact: true }).click()
  await admin.waitForTimeout(2200)
  await expect(stage).toHaveCount(0)
  await play().click()
  await expect.poll(() => audio().evaluate(audio => audio.currentTime)).toBeGreaterThan(0)
  await expect(stage).toHaveAttribute('data-phase', 'intro')
  await expect(stage.locator('p')).toContainText('🎂 ¡Feliz cumpleaños!')
  await expect(stage.locator('h1')).toBeHidden()
  assert.equal(await stage.locator('h1').evaluate(title => title.getAnimations().length), 0, 'The name has no entrance before the generated greeting starts')
  const birthdayEntrance = await stage.locator('p').evaluate(title => title.getAnimations()[0].startTime)
  await expect(stage).toHaveAttribute('data-phase', 'greeting', { timeout: alternateIntro.durationMs + 5000 })
  await expect(stage.getByRole('heading', { name: 'Carlos', exact: true })).toBeVisible()
  const reveal = await stage.evaluate(element => ['p', 'h1'].map((selector) => {
    const target = element.querySelector(selector)
    const effect = target.getAnimations()[0].effect
    return { delay: effect.getTiming().delay, duration: effect.getTiming().duration,
      opacity: effect.getKeyframes().map(frame => frame.opacity), color: getComputedStyle(target).color }
  }))
  assert.deepEqual(reveal, [
    { delay: 0, duration: 2000, opacity: ['0', '1'], color: 'rgb(255, 213, 79)' },
    { delay: 0, duration: 2000, opacity: ['0', '1'], color: 'rgb(255, 213, 79)' },
  ])
  const headingClock = await stage.locator('h1').evaluate(title => ({ start: title.getAnimations()[0].startTime, elapsed: title.getAnimations()[0].currentTime }))
  assert.ok(headingClock.start > birthdayEntrance, 'The name entrance follows the introduction instead of sharing its timer')
  assert.ok(Math.abs(headingClock.elapsed / 1000 - await audio().evaluate(audio => audio.currentTime)) < 0.35, 'The name starts fading when the generated audio actually plays')
  await expect.poll(() => stage.locator('h1').evaluate(title => title.getAnimations()[0]?.playState)).toBe('finished')
  const entranceStart = await stage.locator('h1').evaluate(title => title.getAnimations()[0].startTime)
  assert.equal(await admin.evaluate(() => window.birthdayPreviewBeds.filter(bed => !bed.stopped).length), 1)
  await preview.getByRole('button', { name: 'Pausar', exact: true }).click()
  const pausedAt = await audio().evaluate(audio => audio.currentTime)
  assert.equal(await audio().evaluate(audio => audio.paused), true)
  assert.equal(await admin.evaluate(() => window.birthdayPreviewBeds.filter(bed => !bed.stopped).length), 1, 'Pause holds the same bed source')
  await play().focus()
  await admin.keyboard.press('Enter')
  await expect.poll(() => audio().evaluate(audio => audio.currentTime)).toBeGreaterThan(pausedAt)
  assert.equal(await stage.locator('h1').evaluate(title => title.getAnimations()[0].startTime), entranceStart, 'Pause/resume must not repeat the dedication entrance')
  await admin.emulateMedia({ reducedMotion: 'reduce' })
  await expect.poll(() => stage.locator('video').evaluate(video => video.paused)).toBe(true)
  await expect(stage.locator('video')).toBeVisible()
  await expect(stage.locator('h1')).toBeVisible()
  assert.equal(await stage.evaluate(element => element.getAnimations({ subtree: true }).length), 0)
  await admin.emulateMedia({ reducedMotion: 'no-preference' })
  const abandoned = await audio().elementHandle()
  await introductions.selectOption(before.settings.introId)
  assert.equal(await abandoned.evaluate(audio => audio.paused), true)
  await expect(play()).toBeEnabled()
  await play().click()
  await expect(preview.getByRole('status').filter({ hasText: /^Saludo$/ })).toBeVisible({ timeout: 5000 })
  await expect(stage).toHaveAttribute('data-phase', 'greeting')
  await expect(stage.locator('p')).toContainText('¡Feliz cumpleaños!')
  await expect(stage.getByRole('heading', { name: 'Carlos', exact: true })).toBeVisible()
  await expect(preview.getByRole('status').filter({ hasText: /^Puente musical$/ })).toBeVisible({ timeout: 20000 })
  await expect(stage).toHaveAttribute('data-phase', 'bridge')
  assert.equal(await admin.evaluate(() => window.birthdayPreviewBeds.filter(bed => !bed.stopped).length), 1, 'The bridge retains the same background track')
  await expect(preview.getByRole('status').filter({ hasText: /^Canción de cumpleaños$/ })).toBeVisible({ timeout: 20000 })
  await expect(stage).toHaveAttribute('data-phase', 'music')
  await expect(stage.locator('p')).toContainText('¡Feliz cumpleaños!')
  await expect(stage.getByRole('heading', { name: 'Carlos', exact: true })).toBeVisible()
  assert.equal(await admin.evaluate(() => window.birthdayPreviewBeds.filter(bed => !bed.stopped).length), 0, 'Music plays without accompaniment')
  const mediaLevel = () => audio().evaluate((element) => {
    const media = window.birthdayPreviewMedia.find(media => media.element === element)
    return { elapsed: element.currentTime, gain: media?.gain.gain.value, state: media?.context.state }
  })
  await expect.poll(async () => (await mediaLevel()).elapsed).toBeGreaterThan(0.2)
  const incoming = await mediaLevel()
  assert.ok(incoming.gain > 0 && incoming.gain < 1, 'Native preview music uses a smooth fade-in')
  await preview.getByRole('button', { name: 'Pausar', exact: true }).click()
  await expect.poll(async () => (await mediaLevel()).state).toBe('suspended')
  const held = await mediaLevel()
  await admin.waitForTimeout(350)
  assert.ok(Math.abs((await mediaLevel()).gain - held.gain) < 0.05, 'A paused fade must not advance')
  await play().click()
  await expect.poll(async () => (await mediaLevel()).elapsed).toBeGreaterThan(1.1)
  assert.ok(Math.abs((await mediaLevel()).gain - 1) < 0.05, 'Resume preserves the original fade position instead of replaying it')
  await expect(preview.getByRole('status').filter({ hasText: /^Aplauso de cierre$/ })).toBeVisible({ timeout: 20000 })
  await expect(stage).toHaveAttribute('data-phase', 'applause')
  assert.equal(await admin.evaluate(() => window.birthdayPreviewBeds.filter(bed => !bed.stopped).length), 0, 'Applause never restarts the accompaniment')
  await expect(preview.getByText('Previsualización finalizada', { exact: true })).toBeVisible({ timeout: 20000 })
  assert.equal(calls.length, preparedCount, 'Playback and variant changes reuse the generated sample')
  await preview.getByRole('combobox', { name: 'Probar desde', exact: true }).selectOption('2')
  await expect.poll(() => audio().evaluate(audio => audio.paused)).toBe(false)
  await expect(audio()).toHaveAttribute('src', /api\/birthdays\/assets\//)
  await preview.getByRole('button', { name: 'Reiniciar', exact: true }).click()
  await expect(audio()).toHaveAttribute('src', new RegExp(before.settings.introId))
  await audio().evaluate(audio => audio.dispatchEvent(new Event('error')))
  await expect(preview.getByRole('alert')).toContainText('No se pudo abrir el audio')
  await preview.getByRole('button', { name: 'Reiniciar', exact: true }).click()
  await expect(preview.getByRole('alert')).toHaveCount(0)
  await preview.getByRole('button', { name: 'Pausar', exact: true }).click()
  await preview.getByRole('combobox', { name: 'Perfil de redacción', exact: true }).selectOption('0')
  await expect(play()).toBeEnabled()
  await preview.getByRole('combobox', { name: 'Perfil de redacción', exact: true }).selectOption('')
  await expect(play()).toBeEnabled()
  await name.fill('Lucía')
  await expect(text).toHaveValue(/Lucía/)
  await expect(play()).toBeDisabled()
  await generate.click()
  await expect(play()).toBeEnabled({ timeout: 20000 })
  await preview.getByRole('button', { name: 'Generar otro saludo', exact: true }).click()
  await expect(play()).toBeEnabled({ timeout: 20000 })
  await expect(text).toHaveValue(/^Lucía…/)
  await text.fill('Este texto no incluye el nombre.')
  const invalidCount = calls.length
  await generate.click()
  await expect(preview.getByRole('alert')).toContainText('El saludo no cumple')
  assert.equal(calls.length, invalidCount, 'Invalid text must be rejected before calling providers')
  await name.fill('Carlos')
  await text.fill(preparedText)
  await expect(play()).toBeEnabled()
  for (const width of [390, 1440]) {
    await admin.setViewportSize({ width, height: 900 })
    const longName = 'María Alejandra Valentina Fernanda de los Ángeles'
    await name.fill(longName)
    await generate.click()
    await expect(play()).toBeEnabled({ timeout: 20000 })
    await preview.getByRole('combobox', { name: 'Probar desde', exact: true }).selectOption('2')
    await stage.scrollIntoViewIfNeeded()
    await expect(stage.getByRole('heading', { name: longName, exact: true })).toBeVisible()
    await expect.poll(() => stage.locator('h1').evaluate(title => title.getAnimations()[0]?.playState)).toBe('finished')
    await preview.getByRole('button', { name: 'Pausar', exact: true }).click()
    const measure = () => stage.locator('h1').evaluate((title) => {
      const area = title.closest('section').getBoundingClientRect()
      const bounds = title.getBoundingClientRect()
      return { fits: title.scrollHeight <= parseFloat(getComputedStyle(title).lineHeight) * 2 + 1,
        lower: bounds.top > area.top + area.height / 2, inside: bounds.bottom <= area.bottom,
        background: getComputedStyle(title.parentElement).backgroundColor }
    })
    await expect.poll(async () => (await measure()).fits).toBe(true)
    assert.deepEqual(await measure(), { fits: true, lower: true, inside: true, background: 'rgba(0, 0, 0, 0)' })
    await stage.screenshot({ path: `${data}/birthday-dedication-long-${width}.png` })
    await name.fill('M'.repeat(60))
    await expect.poll(async () => (await measure()).fits).toBe(true)
    await name.fill('Carlos')
    await preview.getByRole('region', { name: 'Cumpleaños de Carlos', exact: true }).scrollIntoViewIfNeeded()
    assert.ok(await preview.evaluate(element => element.scrollWidth <= element.clientWidth + 2))
    await admin.screenshot({ path: `${data}/birthday-preview-${width}.png` })
    await generate.scrollIntoViewIfNeeded()
    await admin.screenshot({ path: `${data}/birthday-preview-controls-${width}.png` })
  }
  await play().click()
  await expect.poll(() => audio().evaluate(audio => audio.paused)).toBe(false)
  const closingAudio = await audio().elementHandle()
  const closingVideo = await preview.locator('video').elementHandle()
  await admin.keyboard.press('Escape')
  await expect(preview).toHaveCount(0)
  assert.equal(await closingAudio.evaluate(audio => audio.paused), true)
  assert.equal(await closingVideo.evaluate(video => video.paused), true)
  assert.equal(await admin.evaluate(() => window.birthdayPreviewBeds.filter(bed => !bed.stopped).length), 0)
  const finalCount = calls.length
  await admin.getByRole('link', { name: 'Historial', exact: true }).click()
  await admin.getByRole('link', { name: 'Configuración', exact: true }).click()
  await admin.getByRole('button', { name: 'Previsualizar cumpleaños', exact: true }).click()
  await expect(name).toHaveValue('Carlos')
  await expect(play()).toBeEnabled()
  const retained = await text.inputValue()
  const modified = 'Carlos, conservamos este último saludo editado al cerrar la ventana. ¡Feliz cumpleaños!'
  await text.fill(modified)
  await expect(play()).toBeDisabled()
  await preview.getByRole('button', { name: 'Cerrar previsualización', exact: true }).click()
  await admin.getByRole('button', { name: 'Previsualizar cumpleaños', exact: true }).click()
  await expect(text).toHaveValue(modified)
  await expect(play()).toBeDisabled()
  await text.fill(retained)
  await expect(play()).toBeEnabled()
  await generate.click()
  assert.equal(calls.length, finalCount, 'Navigation and reopening edited drafts must retain the matching audio')
  const savedPreview = async () => (await api.get(`${base}api/birthdays/preview/1`)).json()
  await expect.poll(async () => (await savedPreview()).draft?.script).toBe(retained)
  await admin.reload()
  await admin.getByRole('button', { name: 'Previsualizar cumpleaños', exact: true }).click()
  await expect(name).toHaveValue('Carlos')
  await expect(text).toHaveValue(retained)
  await expect(play()).toBeEnabled()
  await generate.click()
  assert.equal(calls.length, finalCount, 'A browser refresh restores matching audio without calling providers')
  const restored = await savedPreview()
  assert.ok(Object.values(restored.samples).some(asset => asset.script === retained))
  await text.fill(modified)
  await expect.poll(async () => (await savedPreview()).draft?.script).toBe(modified)
  await admin.reload()
  await admin.getByRole('button', { name: 'Previsualizar cumpleaños', exact: true }).click()
  await expect(text).toHaveValue(modified)
  await expect(play()).toBeDisabled()
  await text.fill(retained)
  await expect(play()).toBeEnabled()
  assert.equal(calls.length, finalCount, 'Recovering edited drafts never silently regenerates audio')
  await name.fill('Valentina')
  await generate.click()
  await expect(play()).toBeEnabled({ timeout: 20000 })
  const namedText = await text.inputValue()
  const namedCount = calls.length
  await expect.poll(async () => (await savedPreview()).draft?.name).toBe('Valentina')
  await admin.reload()
  await admin.getByRole('button', { name: 'Previsualizar cumpleaños', exact: true }).click()
  await expect(name).toHaveValue('Valentina')
  await expect(text).toHaveValue(namedText)
  await expect(play()).toBeEnabled()
  await generate.click()
  assert.equal(calls.length, namedCount, 'A custom name, its exact script and matching audio survive refresh together')
  await preview.getByRole('button', { name: 'Cerrar previsualización', exact: true }).click()
  const after = await snapshot()
  assert.deepEqual(after.settings, before.settings)
  assert.deepEqual(after.events, before.events, 'Preview must not create or change real birthdays')
}
